#!/usr/bin/env bash
# Regenerates requirements.lock: every Python package the production image
# installs, at an exact version with its hashes, resolved for the image
# (Linux x86_64, Python 3.11). Run it after changing requirements.txt and
# commit both files. Needs uv (https://docs.astral.sh/uv/: `pip install uv`).
#
# The lock mirrors the Dockerfile: firebase-admin is installed there with
# --no-deps plus only what its auth module needs, so here it's swapped for
# those packages; RePyability (a git tag, installed --no-deps) isn't in it.
set -euo pipefail
cd "$(dirname "$0")/.."

input=$(mktemp)
trap 'rm -f "$input"' EXIT
grep -viE '^firebase-admin' requirements.txt > "$input"
printf '%s\n' google-auth cachecontrol "pyjwt[crypto]" requests httpx >> "$input"

uv pip compile "$input" \
  --python-version 3.11 --python-platform x86_64-unknown-linux-gnu \
  --generate-hashes --no-header --no-annotate --quiet \
  --output-file requirements.lock.tmp
{
  echo "# Generated by tools/lock_requirements.sh from requirements.txt; don't edit by hand."
  echo "# Exact versions and hashes for the production image (Linux x86_64, Python 3.11)."
  cat requirements.lock.tmp
} > requirements.lock
rm requirements.lock.tmp
echo "requirements.lock: $(grep -cE '^[a-z0-9]' requirements.lock) packages"
